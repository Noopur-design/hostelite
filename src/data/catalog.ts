function highlightsFor(name: string, locality: string, city: string, developer: string) {
  return [
    `Prime location in ${locality}, ${city}`,
    "Spacious and well-ventilated residences",
    "Premium clubhouse with modern amenities",
    "Lush green surroundings",
    `Developed by ${developer} — a trusted name`,
  ];
}

function aboutFor(name: string, locality: string, city: string, developer: string, label: string, status: Status) {
  const when =
    status === "Ready to Move"
      ? "ready for possession"
      : status === "New Launch"
        ? "newly launched"
        : "under construction";
  return `${name} by ${developer} is a ${when} address in ${locality}, ${city}, planned around daylight, privacy and everyday ease. ${label} sit within a gated community with a residents' club, landscaped courts and a calm approach from the main road.`;
}

function row(partial: Omit<Listing, "address" | "highlights" | "about"> & { about?: string; highlights?: string[] }): Listing {
  return {
    ...partial,
    address: `${partial.locality}, ${partial.city}`,
    about:
      partial.about ??
      aboutFor(partial.name, partial.locality, partial.city, partial.developer, partial.bhkLabel, partial.status),
    highlights:
      partial.highlights ?? highlightsFor(partial.name, partial.locality, partial.city, partial.developer),
  };
}

